/// Keyboard mapping used by the desktop frontend.
pub fn pc_key(label: &str) -> Option<(u8, u8)> {
    Some(match label {
        "0" => (0x10, 0x40),
        "1" => (0x01, 0x01),
        "2" => (0x01, 0x02),
        "3" => (0x01, 0x04),
        "4" => (0x02, 0x01),
        "5" => (0x02, 0x02),
        "6" => (0x02, 0x04),
        "7" => (0x04, 0x01),
        "8" => (0x04, 0x02),
        "9" => (0x04, 0x04),
        "." => (0x08, 0x40),
        "+" => (0x01, 0x08),
        "-" => (0x01, 0x10),
        "X" => (0x02, 0x08),
        "/" => (0x02, 0x10),
        "=" | "EXE" | "Return" => (0x01, 0x40),
        "SPACE" => (0x04, 0x10),
        "AC" => (0x04, 0x10),
        "DEL" => (0x04, 0x08),
        "SHIFT" => (0x80, 0x01),
        "ALPHA" => (0x80, 0x02),
        "MODE" => (0x80, 0x10),
        "UP" => (0x80, 0x04),
        "DOWN" => (0x40, 0x08),
        "LEFT" => (0x40, 0x04),
        "RIGHT" => (0x80, 0x08),
        "sin" => (0x10, 0x08),
        "cos" => (0x10, 0x10),
        "tan" => (0x10, 0x20),
        "log" => (0x20, 0x10),
        "ln" => (0x20, 0x20),
        "sqrt" => (0x20, 0x02),
        "x2" => (0x20, 0x04),
        "xn" => (0x20, 0x08),
        "a/b" => (0x20, 0x01),
        "x-1" => (0x40, 0x10),
        "x3" => (0x40, 0x02),
        "Abs" => (0x40, 0x01),
        "(-)" => (0x10, 0x01),
        "hyp" => (0x10, 0x04),
        "dms" => (0x10, 0x02),
        "RCL" => (0x08, 0x01),
        "ENG" => (0x08, 0x02),
        "(" => (0x08, 0x04),
        ")" => (0x08, 0x08),
        "S<>D" => (0x08, 0x10),
        "M+" => (0x08, 0x20),
        "x10" => (0x04, 0x40),
        "Ans" => (0x02, 0x40),
        "logx" => (0x40, 0x20),
        _ => return None,
    })
}
